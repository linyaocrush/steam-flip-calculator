    lang = lang if lang in LANGUAGE_CODES else "zh"
    translations = TRANSLATIONS.get(lang, TRANSLATIONS["zh"])
    text = translations.get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except KeyError:
            pass
    return text